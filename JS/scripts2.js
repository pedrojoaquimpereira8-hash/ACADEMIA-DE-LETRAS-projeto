function calcularMedia(notas) {

    let soma = 0;

    for (let i = 0; i < notas.length; i++) {

        soma = soma + notas[i];

    }

    return soma / notas.length;

}


function adicionarMedias(alunos) {

    for (let i = 0; i < alunos.length; i++) {

        alunos[i].media = calcularMedia(alunos[i].notas);

    }

}


function criarPodio(alunos) {

    let disponiveis = [...alunos];

    const podio = [];

    for (let posicao = 0; posicao < 3; posicao++) {

        let melhor = 0;

        for (let i = 1; i < disponiveis.length; i++) {

            if (disponiveis[i].media > disponiveis[melhor].media) {

                melhor = i;

            }

        }

        podio.push(disponiveis[melhor]);

        disponiveis.splice(melhor, 1);

    }

    return podio;

}

